using Krios.Models.Krios;
using Krios.Utils;
using System.Data.Common;

namespace Krios.Services.Krios
{
    public class AssetService
    {
        public const int MaxImageBytes = 5 * 1024;
        private static bool tableReady;
        private readonly IDbProvider dbprovider;
        private readonly IQueryBuilderProvider querybuilderprovider;
        private readonly RequestState requeststate;

        public AssetService(
            IDbProvider dbprovider,
            IQueryBuilderProvider querybuilderprovider,
            RequestState requeststate)
        {
            this.dbprovider = dbprovider;
            this.querybuilderprovider = querybuilderprovider;
            this.requeststate = requeststate;
        }

        public async Task EnsureTable(IDb db)
        {
            if (tableReady) return;
            var cmd = db.GetCommand(@"
                CREATE TABLE IF NOT EXISTS assets (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  ""orgId"" BIGINT NOT NULL,
                  ""locationId"" BIGINT,
                  kind VARCHAR(64),
                  ""mimeType"" VARCHAR(128),
                  content TEXT,
                  createdby VARCHAR(255),
                  createdon DATE,
                  updatedby VARCHAR(255),
                  updatedon DATE
                );
                CREATE INDEX IF NOT EXISTS idx_assets_org ON assets (""orgId"");
            ");
            await db.ExecuteNonQuery(cmd);
            tableReady = true;
        }

        public async Task<List<Asset>> Select(AssetSelectReq req)
        {
            using IDb db = await dbprovider.GetDb();
            await db.Connect();
            return await SelectTransaction(db, req);
        }

        public async Task<List<Asset>> SelectTransaction(IDb db, AssetSelectReq req)
        {
            await EnsureTable(db);
            const string query = @"
                SELECT id, ""orgId"", ""locationId"", kind, ""mimeType"", content, createdby, createdon, updatedby, updatedon
                FROM assets
            ";
            var qb = querybuilderprovider.GetQueryBuilder(query);
            if (req.id > 0)
                qb.AddParameter("id", "=", "id", req.id, DbTypes.Types.Long);
            if (req.orgId > 0)
                qb.AddParameter(@"""orgId""", "=", "orgId", req.orgId, DbTypes.Types.Long);
            if (req.locationId > 0)
                qb.AddParameter(@"""locationId""", "=", "locationId", req.locationId, DbTypes.Types.Long);
            if (!string.IsNullOrWhiteSpace(req.kind))
                qb.AddParameter("kind", "=", "kind", req.kind, DbTypes.Types.String);
            qb.AddOrderBy(QueryBuilder.Order.ASC, "id");
            var command = qb.GetCommand(db);
            var result = new List<Asset>();
            using DbDataReader reader = await db.Execute(command);
            while (await reader.ReadAsync())
                result.Add(Map(reader));
            return result;
        }

        public async Task<Asset?> GetById(long id)
        {
            if (id <= 0) return null;
            var rows = await Select(new AssetSelectReq { id = id });
            return rows.FirstOrDefault();
        }

        public async Task<Asset> Insert(Asset entity)
        {
            using IDb db = await dbprovider.GetDb();
            await db.Connect();
            await InsertTransaction(db, entity);
            return entity;
        }

        public async Task InsertTransaction(IDb db, Asset entity)
        {
            await EnsureTable(db);
            NormalizeImage(entity);
            const string query = @"
                INSERT INTO assets (""orgId"", ""locationId"", kind, ""mimeType"", content, createdby, createdon, updatedby, updatedon)
                VALUES (@orgId, @locationId, @kind, @mimeType, @content, @createdby, @createdon, @updatedby, @updatedon)
                RETURNING id;
            ";
            var today = DateTime.UtcNow.Date;
            var actor = requeststate.usercontext.id > 0 ? requeststate.usercontext.id.ToString() : "system";
            if (entity.createdon == null) entity.createdon = today;
            if (entity.updatedon == null) entity.updatedon = today;
            if (string.IsNullOrWhiteSpace(entity.createdby)) entity.createdby = actor;
            if (string.IsNullOrWhiteSpace(entity.updatedby)) entity.updatedby = actor;
            if (string.IsNullOrWhiteSpace(entity.kind)) entity.kind = "logo";

            var cmd = db.GetCommand(query);
            Bind(cmd, db, entity, includeId: false);
            using var reader = await db.Execute(cmd);
            if (await reader.ReadAsync())
                entity.id = Convert.ToInt64(reader["id"]);
        }

        public async Task<Asset> Update(Asset entity)
        {
            using IDb db = await dbprovider.GetDb();
            await db.Connect();
            await UpdateTransaction(db, entity);
            return entity;
        }

        public async Task<bool> UpdateTransaction(IDb db, Asset entity)
        {
            await EnsureTable(db);
            NormalizeImage(entity);
            const string query = @"
                UPDATE assets SET
                    ""orgId"" = @orgId,
                    ""locationId"" = @locationId,
                    kind = @kind,
                    ""mimeType"" = @mimeType,
                    content = @content,
                    createdby = @createdby,
                    createdon = @createdon,
                    updatedby = @updatedby,
                    updatedon = @updatedon
                WHERE id = @id
            ";
            entity.updatedon = DateTime.UtcNow.Date;
            entity.updatedby = requeststate.usercontext.id > 0 ? requeststate.usercontext.id.ToString() : entity.updatedby;
            var cmd = db.GetCommand(query);
            Bind(cmd, db, entity, includeId: true);
            return await db.ExecuteNonQuery(cmd) > 0;
        }

        public async Task<bool> Delete(AssetDeleteReq req)
        {
            using IDb db = await dbprovider.GetDb();
            await db.Connect();
            await EnsureTable(db);
            var cmd = db.GetCommand(@"DELETE FROM assets WHERE id = @id");
            db.AddParameter(cmd, "id", DbTypes.Types.Long).Value = req.id;
            return await db.ExecuteNonQuery(cmd) > 0;
        }

        /// <summary>If value is a data URL, store it as an asset and return the new id. If it is already an id, keep it.</summary>
        public async Task<string> StoreImageId(IDb db, long orgId, string? value, string kind = "logo")
        {
            var raw = (value ?? "").Trim();
            if (string.IsNullOrEmpty(raw)) return "";
            if (!raw.StartsWith("data:image/", StringComparison.OrdinalIgnoreCase))
                return raw;
            var asset = new Asset
            {
                orgId = orgId,
                kind = kind,
                content = raw,
            };
            await InsertTransaction(db, asset);
            return asset.id.ToString();
        }

        public static (byte[] bytes, string mime)? TryDecodeImage(string? content)
        {
            var raw = (content ?? "").Trim();
            if (!raw.StartsWith("data:image/", StringComparison.OrdinalIgnoreCase)) return null;
            var comma = raw.IndexOf(',');
            if (comma < 0) return null;
            var header = raw[..comma];
            var mimePart = header.StartsWith("data:", StringComparison.OrdinalIgnoreCase) ? header[5..] : header;
            var semi = mimePart.IndexOf(';');
            var mime = (semi > 0 ? mimePart[..semi] : mimePart).Trim();
            if (string.IsNullOrWhiteSpace(mime)) mime = "image/png";
            try
            {
                var bytes = Convert.FromBase64String(raw[(comma + 1)..]);
                if (bytes.Length == 0 || bytes.Length > MaxImageBytes) return null;
                return (bytes, mime);
            }
            catch
            {
                return null;
            }
        }

        private static void NormalizeImage(Asset entity)
        {
            var decoded = TryDecodeImage(entity.content);
            if (decoded == null)
                throw new InvalidOperationException("Upload an image smaller than 5 KB");
            entity.content = entity.content.Trim();
            if (string.IsNullOrWhiteSpace(entity.mimeType))
                entity.mimeType = decoded.Value.mime;
        }

        private static Asset Map(DbDataReader reader)
        {
            return new Asset
            {
                id = Convert.ToInt64(reader["id"]),
                orgId = reader["orgId"] == DBNull.Value ? 0 : Convert.ToInt64(reader["orgId"]),
                locationId = reader["locationId"] == DBNull.Value ? 0 : Convert.ToInt64(reader["locationId"]),
                kind = reader["kind"]?.ToString() ?? "",
                mimeType = reader["mimeType"]?.ToString() ?? "",
                content = reader["content"]?.ToString() ?? "",
                createdby = reader["createdby"]?.ToString() ?? "",
                createdon = reader["createdon"] == DBNull.Value ? null : Convert.ToDateTime(reader["createdon"]),
                updatedby = reader["updatedby"]?.ToString() ?? "",
                updatedon = reader["updatedon"] == DBNull.Value ? null : Convert.ToDateTime(reader["updatedon"]),
            };
        }

        private static void Bind(DbCommand cmd, IDb db, Asset entity, bool includeId)
        {
            if (includeId)
                db.AddParameter(cmd, "id", DbTypes.Types.Long).Value = entity.id;
            db.AddParameter(cmd, "orgId", DbTypes.Types.Long).Value = entity.orgId;
            db.AddParameter(cmd, "locationId", DbTypes.Types.Long).Value = entity.locationId;
            db.AddParameter(cmd, "kind", DbTypes.Types.String).Value = entity.kind ?? "";
            db.AddParameter(cmd, "mimeType", DbTypes.Types.String).Value = entity.mimeType ?? "";
            db.AddParameter(cmd, "content", DbTypes.Types.String).Value = entity.content ?? "";
            db.AddParameter(cmd, "createdby", DbTypes.Types.String).Value = entity.createdby ?? "";
            db.AddParameter(cmd, "createdon", DbTypes.Types.Date).Value = entity.createdon ?? DateTime.UtcNow.Date;
            db.AddParameter(cmd, "updatedby", DbTypes.Types.String).Value = entity.updatedby ?? "";
            db.AddParameter(cmd, "updatedon", DbTypes.Types.Date).Value = entity.updatedon ?? DateTime.UtcNow.Date;
        }
    }
}
