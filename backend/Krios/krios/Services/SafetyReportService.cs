using Krios.Models.Krios;
using Krios.Utils;

namespace Krios.Services.Krios
{
    public class SafetyReportService
    {
        private static readonly HashSet<string> Reasons = new(StringComparer.OrdinalIgnoreCase)
        {
            "child-safety",
            "sexual-exploitation",
            "inappropriate-content",
            "harassment-grooming",
            "other",
        };

        private static bool tableReady;
        private readonly IDbProvider dbprovider;
        private readonly RequestState requeststate;
        private readonly OtpMailer mailer;
        private readonly ILogger<SafetyReportService> logger;

        public SafetyReportService(
            IDbProvider dbprovider,
            RequestState requeststate,
            OtpMailer mailer,
            ILogger<SafetyReportService> logger)
        {
            this.dbprovider = dbprovider;
            this.requeststate = requeststate;
            this.mailer = mailer;
            this.logger = logger;
        }

        public async Task EnsureTable(IDb db)
        {
            if (tableReady) return;
            var cmd = db.GetCommand(@"
                CREATE TABLE IF NOT EXISTS ""safetyReports"" (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  ""reporterId"" BIGINT,
                  ""reporterContact"" VARCHAR(255),
                  ""reportedUserId"" BIGINT,
                  ""reportedContentId"" VARCHAR(255),
                  reason VARCHAR(64) NOT NULL,
                  description TEXT,
                  evidence TEXT,
                  status VARCHAR(32) NOT NULL DEFAULT 'open',
                  ""moderatorAction"" TEXT,
                  ""resolvedOn"" DATE,
                  createdby VARCHAR(255),
                  createdon TIMESTAMP,
                  updatedby VARCHAR(255),
                  updatedon TIMESTAMP
                );
                CREATE INDEX IF NOT EXISTS idx_safety_reports_status ON ""safetyReports"" (status);
            ");
            await db.ExecuteNonQuery(cmd);
            tableReady = true;
        }

        public async Task<SafetySubmitRes> Submit(SafetySubmitReq req)
        {
            var reason = (req.reason ?? "").Trim().ToLowerInvariant();
            if (!Reasons.Contains(reason))
                throw new AppException(AppException.ErrorCodes.BadRequest, "Select a report reason.");

            var description = Clip(req.description, 4000);
            if (string.IsNullOrWhiteSpace(description))
                throw new AppException(AppException.ErrorCodes.BadRequest, "Describe what you saw so we can review it.");

            var reporterId = req.reporterId > 0
                ? req.reporterId
                : requeststate.usercontext.id;
            if (reporterId < 0) reporterId = 0;
            var reporterContact = Clip(req.reporterContact, 255);
            var reportedUserId = req.reportedUserId;
            var reportedContentId = Clip(req.reportedContentId, 255);
            var evidence = Clip(req.evidence, 1000);
            var now = DateTime.UtcNow;
            var actor = reporterId > 0 ? reporterId.ToString() : "anonymous";

            using IDb db = await dbprovider.GetDb();
            await db.Connect();
            await EnsureTable(db);

            const string query = @"
                INSERT INTO ""safetyReports"" (
                    ""reporterId"", ""reporterContact"", ""reportedUserId"", ""reportedContentId"",
                    reason, description, evidence, status, createdby, createdon, updatedby, updatedon
                )
                VALUES (
                    @reporterId, @reporterContact, @reportedUserId, @reportedContentId,
                    @reason, @description, @evidence, 'open', @createdby, @createdon, @updatedby, @updatedon
                )
                RETURNING id;
            ";

            var cmd = db.GetCommand(query);
            db.AddParameter(cmd, "reporterId", DbTypes.Types.Long).Value = reporterId;
            db.AddParameter(cmd, "reporterContact", DbTypes.Types.String).Value = reporterContact;
            db.AddParameter(cmd, "reportedUserId", DbTypes.Types.Long).Value = reportedUserId;
            db.AddParameter(cmd, "reportedContentId", DbTypes.Types.String).Value = reportedContentId;
            db.AddParameter(cmd, "reason", DbTypes.Types.String).Value = reason;
            db.AddParameter(cmd, "description", DbTypes.Types.String).Value = description;
            db.AddParameter(cmd, "evidence", DbTypes.Types.String).Value = evidence;
            db.AddParameter(cmd, "createdby", DbTypes.Types.String).Value = actor;
            db.AddParameter(cmd, "createdon", DbTypes.Types.DateTime).Value = now;
            db.AddParameter(cmd, "updatedby", DbTypes.Types.String).Value = actor;
            db.AddParameter(cmd, "updatedon", DbTypes.Types.DateTime).Value = now;

            long reportId = 0;
            using (var reader = await db.Execute(cmd))
            {
                if (await reader.ReadAsync())
                    reportId = Convert.ToInt64(reader["id"]);
            }

            try
            {
                var inbox = mailer.ChildSafetyInbox;
                if (mailer.IsConfigured && OtpMailer.IsDeliverableEmail(inbox))
                {
                    await mailer.Send(
                        inbox,
                        $"Krios child safety report #{reportId}",
                        $"A safety report was submitted and is open for review. Do not treat this as confirmed abuse.\n\n" +
                        $"Report ID: {reportId}\n" +
                        $"Reason: {reason}\n" +
                        $"Reporter ID: {reporterId}\n" +
                        $"Reporter contact: {reporterContact}\n" +
                        $"Reported user ID: {reportedUserId}\n" +
                        $"Reported content ID: {reportedContentId}\n" +
                        $"Submitted (UTC): {now:o}\n\n" +
                        $"Description:\n{description}\n\n" +
                        $"Evidence / URL:\n{evidence}\n");
                }
            }
            catch (Exception ex)
            {
                logger.LogError(ex, "Could not email child safety report {ReportId}", reportId);
            }

            return new SafetySubmitRes
            {
                reportId = reportId,
                status = "open",
                message = "Report submitted. Our safety team will review it. This is not a finding of confirmed abuse.",
            };
        }

        private static string Clip(string? value, int max)
        {
            var text = (value ?? "").Trim();
            return text.Length <= max ? text : text[..max];
        }
    }
}
